def validate_jsx(jsx):
    """Custom JSX sanity check: DATA parses as JSON, brackets balance, tags nest correctly, required parts exist."""
    m = re.search(r"const DATA = (\{.*?\n\});\n", jsx, re.S)
    if not m:
        raise ValueError("DATA block not found")
    json.loads(m.group(1))
    code = jsx[m.end():]
    code = re.sub(r"//[^\n]*", "", code)
    code = re.sub(r'"(?:\\.|[^"\\])*"', '""', code)
    stack = []
    pairs = {")": "(", "]": "[", "}": "{"}
    for ch in code:
        if ch in "([{":
            stack.append(ch)
        elif ch in pairs:
            if not stack or stack.pop() != pairs[ch]:
                raise ValueError("unbalanced bracket " + ch)
    if stack:
        raise ValueError("unclosed bracket(s): " + "".join(stack))
    tags = []
    for t in re.finditer(r"<(/?)([A-Za-z][\w.]*)([^<>]*?)(/?)>", code):
        close, name, attrs, selfclose = t.groups()
        if selfclose or name in ("br", "img", "hr", "input", "meta", "link"):
            continue
        if close:
            if not tags or tags.pop() != name:
                raise ValueError("mismatched closing tag </%s>" % name)
        else:
            tags.append(name)
    if tags:
        raise ValueError("unclosed tag(s): %s" % tags)
    for need in ("function App", "ReactDOM.createRoot", "function Hero", "function Features", "function Steps", "function Faq", "function Highlights", "function Pricing", "function Team", "function Testimonials", "function Blog"):
        if need not in code:
            raise ValueError("missing " + need)
    return True


def generate_site(content, assets, out_dir, seed=None):
    rng = random.Random(None if seed is None else seed + 2)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    jsx, layout = build_jsx(content, assets, rng)
    validate_jsx(jsx)
    from .asset_engine import data_uri
    fav = data_uri(assets["logo"])
    meta = {"lang": content.get("lang", "en"), "title": html.escape(content["brand"] + " | " + content["hero_heading"]), "description": html.escape(content["tagline"], quote=True), "favicon": fav}
    files = {
        "App.jsx": jsx,
        "styles.css": build_css(assets, rng, content["mood"]),
        "index.html": INDEX_TEMPLATE.substitute(**meta),
        "preview.html": PREVIEW_TEMPLATE.substitute(body=build_preview_body(content, assets, layout), **meta),
    }
    for name, text in files.items():
        (out / name).write_text(text, encoding="utf-8")
    return {"dir": str(out), "files": sorted(files), "layout": layout}
