def _parse(word):
    """-> list of units: C cluster {conj:[(ch, nukta)], end_virama, marks}, V vowel, D digit, P punctuation."""
    units = []
    cur = None
    pending_virama = False
    for ch in word:
        if ch in _COMPOSED_NUKTA or ch in _CONSONANTS:
            item = (_COMPOSED_NUKTA[ch], True) if ch in _COMPOSED_NUKTA else (ch, False)
            if cur is not None and cur["kind"] == "C" and pending_virama:
                cur["conj"].append(item)
                cur["end_virama"] = False
            else:
                cur = {"kind": "C", "conj": [item], "end_virama": False, "marks": []}
                units.append(cur)
            pending_virama = False
        elif ch == _NUKTA:
            if cur is not None and cur["kind"] == "C" and cur["conj"] and not cur["marks"]:
                cur["conj"][-1] = (cur["conj"][-1][0], True)
            pending_virama = False
        elif ch == _VIRAMA:
            if cur is not None and cur["kind"] == "C" and cur["conj"] and not cur["marks"]:
                pending_virama = True
                cur["end_virama"] = True
        elif ch in _VOWELS:
            cur = {"kind": "V", "vowel": ch, "marks": []}
            units.append(cur)
            pending_virama = False
        elif ch in _MATRAS:
            if cur is None:
                cur = {"kind": "C", "conj": [], "end_virama": False, "marks": []}
                units.append(cur)
            cur["marks"].append(_MATRAS[ch])
            if cur["kind"] == "C":
                cur["end_virama"] = False
            pending_virama = False
        elif ch in _DIGITS:
            units.append({"kind": "D", "ch": ch})
            cur = None
            pending_virama = False
        elif ch in _PUNCT:
            units.append({"kind": "P", "ch": ch})
            cur = None
            pending_virama = False
    return units


