def _cluster(u):
    """-> (strokes, headline (x0, x1) or None, width). Local coordinates start at 0."""
    marks = list(u["marks"])
    strokes = []
    if u["kind"] == "V":
        ch = u["vowel"]
        if ch in _COMPOSE:
            base, extra = _COMPOSE[ch]
            marks = extra + marks
        else:
            base = ch
        conj = [(base, False)]
        reph = False
    else:
        conj = list(u["conj"])
        reph = False
        if len(conj) >= 2 and conj[0] == ("र", False):
            reph = True
            conj = conj[1:]
    rakar = False
    if len(conj) >= 2 and conj[-1] == ("र", False):
        rakar = True
        conj = conj[:-1]
    pen = 1.55 if "i" in marks else 0.0
    if not conj:                                   # a stray sign: give it a blank base
        right_extent, last_s, last_anc, last_bot, last_c = 2.0, None, 1.2, 1.0, 1.0
    else:
        n = len(conj)
        i = 0
        while i < n:
            ch, nk = conj[i]
            if i == n - 2 and (ch, conj[i + 1][0]) in _LIG and not nk and not conj[i + 1][1] and not rakar:
                lig = _LIG[(ch, conj[i + 1][0])]
                W, s, lst = lig[0], lig[1], lig[2]
                anc = lig[3] if len(lig) > 3 else s
                lst = [list(p) for p in lst] + ([[(s, HEAD), (s, 0.0)]] if s is not None else [])
                strokes += _shift(lst, pen)
                last_W, last_s, last_anc, last_bot = W, s, anc, _min_y(lst)
                last_c = s if s is not None else W * 0.5
                last_pen = pen
                i += 2
                break
            half = i < n - 1
            W, st, s, anc, bot = _letter(ch, nk, half, rakar and i == n - 1)
            strokes += _shift(st, pen)
            if half:
                if ch in _HALF or _C[ch][1] is not None:
                    pen += W + HGAP
                else:
                    pen += W + GAP
            else:
                last_W, last_s, last_anc, last_bot = W, s, anc, bot
                last_c = s if s is not None else W * 0.5
                last_pen = pen
                if rakar and ch not in _RLIG:
                    strokes += _shift(_rakar(ch, s, W, bot), pen)
                if u["kind"] == "C" and u.get("end_virama") and not marks:
                    if s is not None:
                        strokes += _shift(_halant_stem(s), pen)
                    else:
                        strokes += _shift(_halant(W * 0.5, bot), pen)
            i += 1
        right_extent = last_pen + last_W
        last_c = last_pen + last_c
        last_anc = last_pen + last_anc
        last_s = last_pen + last_s if last_s is not None else None
    stem_x = last_anc
    head_x1 = right_extent
    # --- vowel signs
    aa_x = None
    above = []
    emark = None                                   # ("e"|"ai", x of its foot)
    for m in marks:
        if m in ("aa", "o", "au", "candra_o"):
            aa_x = right_extent + 1.4 if aa_x is None else aa_x
    if aa_x is not None:
        strokes.append([(aa_x, HEAD), (aa_x, 0.0)])
        head_x1 = aa_x + 0.2
        right_extent = aa_x + 0.2
    low = 0.0 if last_s is not None else max(min(0.0, last_bot + 0.4), -0.8)   # stemless letters: lower signs hang below the body
    for m in marks:
        if m == "i":
            hw = max(4.6, min(15.4, 0.95 * right_extent))
            strokes.append([(0.0, 0.0), (0.0, HEAD)])
            strokes += _scale_x(_I_ARC, hw / 9.07)
        elif m in ("ii", "ii_hook"):
            xs = right_extent + 1.4 if m == "ii" else stem_x
            if m == "ii":
                strokes.append([(xs, HEAD), (xs, 0.0)])
                head_x1 = max(head_x1, xs + 0.2)
                right_extent = xs + 0.2
            strokes += _shift(_II_HOOK, xs)
        elif m == "u":
            c = last_c + (0.2 if rakar else 0.0)
            strokes += _shift(_U, c, low - (0.9 if rakar else 0.0))
        elif m in ("uu", "uu_tail"):
            c = last_c + (0.2 if rakar else 0.0)
            strokes += _shift(_UU, c, low - (0.9 if rakar else 0.0))
        elif m == "r":
            c = last_c + (0.2 if rakar else 0.0)
            strokes += _shift(_RV, c, low - (0.9 if rakar else 0.0))
        elif m in ("e", "ai", "o", "au"):
            xe = aa_x if m in ("o", "au") else stem_x
            emark = ("e" if m in ("e", "o") else "ai", xe)
        elif m in ("candra_o", "candra_e"):
            xe = (aa_x - 0.4) if m == "candra_o" else stem_x
            above += _shift(_CUP, xe)
        elif m == "candra":
            xc = aa_x if aa_x is not None else stem_x
            above += _shift(_CUP_DOT, xc)
            above.append(_dot(xc, 8.66))
        elif m == "bindu":
            if emark is not None:
                above.append(_dot(emark[1] + 0.5, 8.42))
            else:
                xc = aa_x if aa_x is not None else stem_x
                above.append(_dot(xc + 0.4, 7.9))
        elif m == "visarga":
            xv = right_extent + 1.4
            strokes.append(_dot(xv, 3.93))
            strokes.append(_dot(xv, 1.37))
            right_extent = xv
    if emark is not None:
        kind, xe = emark
        if reph and conj:
            above += _shift(_E_REPH if kind == "e" else _AI_REPH, xe)
            reph = False
        else:
            above += _e_mark(xe) if kind == "e" else _ai_marks(xe)
    if reph and conj:
        above += _reph(stem_x)
    strokes += above
    head = None
    if conj or u["kind"] == "V" or marks:
        head = (0.0, max(head_x1, 0.5))
    width = max([x for st in strokes for x, _ in st] + [right_extent if conj else 0.0])
    return strokes, head, width


def layout_word(word):
    units = _parse(word)
    out, spans = [], []
    pen = 0.0
    cur_span = None
    for u in units:
        if u["kind"] in ("C", "V"):
            st, head, w = _cluster(u)
            out += _shift(st, pen)
            if head is not None:
                x0, x1 = pen + head[0], pen + head[1]
                if cur_span is None:
                    cur_span = [x0, x1]
                else:
                    cur_span[1] = x1
            elif cur_span is not None:
                spans.append(cur_span)
                cur_span = None
            pen += w + GAP
        else:
            if cur_span is not None:
                spans.append(cur_span)
                cur_span = None
            w, st = _DIGITS[u["ch"]] if u["kind"] == "D" else _PUNCT[u["ch"]]
            out += _shift(st, pen)
            pen += w + GAP
    if cur_span is not None:
        spans.append(cur_span)
    for a, b in spans:
        out.append([(a, HEAD), (b, HEAD)])
    xs = [x for st in out for x, _ in st]
    if not xs:
        return 0.0, []
    lo, hi = min(xs), max(xs)
    if lo < 0:
        out = _shift(out, -lo)
        hi -= lo
    return hi, out
