def _rakar(ch, s, W, bot):
    if ch in _RK:
        return [_RK[ch]]
    if s is not None:
        return _shift([_RK["ग"]], s - _C["ग"][1])
    return _shift(_CARET, W * 0.5, min(0.0, bot))


