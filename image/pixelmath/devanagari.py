def _sp(pts, n=4):
    """Smooth Catmull-Rom curve through the given points."""
    if len(pts) < 3:
        return [tuple(p) for p in pts]
    p = [pts[0]] + list(pts) + [pts[-1]]
    out = [tuple(pts[0])]
    for i in range(1, len(p) - 2):
        p0, p1, p2, p3 = p[i - 1], p[i], p[i + 1], p[i + 2]
        for k in range(1, n + 1):
            t = k / n
            t2, t3 = t * t, t * t * t
            out.append(tuple(0.5 * ((2 * p1[j]) + (-p0[j] + p2[j]) * t + (2 * p0[j] - 5 * p1[j] + 4 * p2[j] - p3[j]) * t2
                                    + (-p0[j] + 3 * p1[j] - 3 * p2[j] + p3[j]) * t3) for j in (0, 1)))
    return out


def _clip_x(strokes, xmax):
    """Keep the parts of the polylines with x <= xmax (interpolating at the cut)."""
    out = []
    for st in strokes:
        cur = []
        for i, (x, y) in enumerate(st):
            inside = x <= xmax
            if i > 0:
                px, py = st[i - 1]
                if (px <= xmax) != inside:
                    t = (xmax - px) / (x - px)
                    cut = (xmax, py + t * (y - py))
                    if inside:
                        cur = [cut]
                    else:
                        cur.append(cut)
                        if len(cur) > 1:
                            out.append(cur)
                        cur = []
            if inside:
                cur.append((x, y))
        if len(cur) > 1:
            out.append(cur)
    return out


def _shift(strokes, dx, dy=0.0):
    return [[(x + dx, y + dy) for x, y in st] for st in strokes]


def _scale_x(strokes, f):
    return [[(x * f, y) for x, y in st] for st in strokes]


def _dot(x, y):
    return [(x, y), (x, y + 0.02)]


