"""A small set of common Chinese characters as stroke data.

Interface used by pixelmath/text.py:
    supports(ch)  -> True if the character is in the table
    strokes(ch)   -> list of polylines [(x, y), ...] in glyph units inside the box x 0..6, y 0..6 (y up, baseline 0)
    ADVANCE       -> horizontal advance of one character in glyph units (box width + side bearing)

Every character is hand-built from stroke helpers (monoline, round caps are added by the renderer).
Only characters that stay legible at ~32 px and ~64 px height are included.
"""
ADVANCE = 6.8
WEIGHT = 0.6           # characters are drawn with thinner strokes than Latin letters so dense ones stay legible


# ---------------------------------------------------------------- stroke helpers
def bez(p0, c, p1, n=8):
    return [((1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * c[0] + t * t * p1[0],
             (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * c[1] + t * t * p1[1])
            for t in [k / n for k in range(n + 1)]]


def hl(x0, x1, y, rise=0.12):
    """horizontal stroke, slightly rising to the right"""
    return [(x0, y), (x1, y + rise)]


def vl(x, y0, y1):
    return [(x, y0), (x, y1)]


def pie(x0, y0, x1, y1, k=0.55):
    """left-falling stroke from (x0, y0) top to (x1, y1) bottom-left"""
    return bez((x0, y0), (x0, y0 - k * (y0 - y1)), (x1, y1))


def na(x0, y0, x1, y1):
    """right-falling stroke from (x0, y0) top-left to (x1, y1) bottom-right"""
    return bez((x0, y0), (x0 + 0.3 * (x1 - x0), y1 + 0.28 * (y0 - y1)), (x1, y1))


def dot(x, y, dx=0.55, dy=-0.8):
    return [(x, y), (x + dx, y + dy)]


def rect(x0, y0, x1, y1):
    return [(x0, y1), (x0, y0), (x1, y0), (x1, y1), (x0, y1)]


def hook(x, y0, y1, hx=-0.6, hy=0.5):
    """vertical stroke with a small hook to the left at the bottom"""
    return [(x, y0), (x, y1 + 0.1), (x + hx, y1 + hy)]


def place(strokes, x0, y0, x1, y1):
    """strokes defined in the unit box 0..1 -> sub-box"""
    return [[(x0 + (x1 - x0) * px, y0 + (y1 - y0) * py) for px, py in s] for s in strokes]


def ren(x=0.0):
    """single-person radical (left component), occupies x .. x+1.7"""
    return [bez((x + 1.6, 5.9), (x + 1.2, 4.6), (x + 0.2, 3.7)), vl(x + 1.0, 4.7, 0.0)]


def nv(x=0.0):
    """woman radical, occupies x .. x+3.4"""
    return [bez((x + 2.0, 5.9), (x + 0.8, 4.7), (x + 0.5, 3.5)) + [(x + 1.5, 3.2), (x + 2.9, 1.4)],
            pie(x + 2.4, 4.6, x + 0.2, 0.2, 0.4), hl(x, x + 3.4, 3.1, 0.1)]


def zi(x=0.0):
    """child radical, occupies x .. x+2.7"""
    return [[(x + 0.2, 5.7), (x + 2.5, 5.7), (x + 1.2, 4.2)], hook(x + 1.2, 4.7, 0.0, -0.6, 0.5), hl(x, x + 2.6, 2.7, 0.1)]


def fit(strokes, x0, y0, x1, y1):
    """scale/translate a stroke set so its bounding box becomes (x0, y0)-(x1, y1)"""
    xs = [p[0] for st in strokes for p in st]
    ys = [p[1] for st in strokes for p in st]
    ax, ay, bx, by = min(xs), min(ys), max(xs), max(ys)
    sx = (x1 - x0) / max(bx - ax, 1e-6)
    sy = (y1 - y0) / max(by - ay, 1e-6)
    return [[(x0 + (px - ax) * sx, y0 + (py - ay) * sy) for px, py in st] for st in strokes]


def top_dot(x=3.0):
    return dot(x, 6.0, 0.25, -0.5)


def roof(y=4.8, t=0.7, x0=0.6, x1=5.4):
    """cap radical stroke (like the roof of 宀): horizontal with short ticks hanging down at both ends"""
    return [(x0, y - t), (x0, y), (x1, y), (x1, y - t)]


def shui(x=0.0):
    """three-dots water radical, occupies x .. x+1.6"""
    return [[(x + 0.7, 5.8), (x + 1.3, 5.1)], [(x + 0.4, 4.0), (x + 1.0, 3.3)], [(x + 0.2, 1.4), (x + 1.5, 2.6)]]


def cao(x0, x1, y):
    """grass radical: bar at y with two ticks crossing it"""
    return [hl(x0, x1, y, 0.1), vl(x0 + (x1 - x0) * 0.33, y + 0.5, y - 0.7), vl(x0 + (x1 - x0) * 0.67, y + 0.5, y - 0.7)]


def shi():
    """food radical 饣, occupies x 0 .. 1.9"""
    return [[(1.9, 5.9), (0.5, 4.8)], [(0.5, 4.9), (1.8, 4.9), (1.6, 4.3)], [(0.6, 4.2), (0.6, 0.3), (1.8, 1.2)]]


def jin(x, w):
    """axe component 斤 starting at x with width w"""
    return [hl(x, x + w, 5.3, 0.1), [(x + 0.45, 5.3), (x + 0.0, 3.7)], hl(x + 0.15, x + 0.62 * w, 3.7, 0.1), vl(x + 0.62 * w, 5.3, 0.0)]


